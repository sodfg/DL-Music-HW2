"""Small, matched-duration SI pilot using the official MusDr implementation.

This produces a separate pilot report, NOT a full-dataset SI estimate.
Requires audio generated by render_audio.py, including its verified manifest.
"""
import argparse
import csv
import hashlib
import importlib.metadata
import json
import math
from pathlib import Path
import statistics
import sys
import time
import wave


def file_hash(path):
    digest=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda:stream.read(1024*1024),b''):
            digest.update(chunk)
    return digest.hexdigest()


def save_json(path,data):
    path=Path(path)
    path.parent.mkdir(parents=True,exist_ok=True)
    temp=path.with_suffix('.json.tmp')
    temp.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
    temp.replace(path)


def si_values(fitness, feature_rate, duration, bounds=(3,8,15)):
    """Same indexing/max rule as MusDr compute_structure_indicator.

    Explicitly bound the long range by the analyzed audio duration. We avoid
    importing unrelated event-metric modules solely to read a NumPy matrix.
    """
    import numpy as np
    if not math.isfinite(feature_rate) or feature_rate<=0:
        raise ValueError('Feature rate must be positive and finite')
    if len(bounds)!=3 or not 0<bounds[0]<bounds[1]<bounds[2]<duration:
        raise ValueError('Need 0 < short < mid < long < analyzed duration')
    if fitness.ndim!=2 or fitness.shape[0]!=fitness.shape[1] or not np.isfinite(fitness).all():
        raise ValueError('Invalid fitness matrix')
    output={}
    for label,low,high in zip(('short','mid','long'),bounds,(*bounds[1:],duration)):
        first=max(0,int(low*feature_rate)-1)
        stop=min(fitness.shape[0],int(high*feature_rate))
        if first>=stop:
            raise ValueError(f'Not enough feature frames for SI_{label}')
        output['SI_'+label]=float(np.max(fitness[first:stop]))
    return output


def verified_audio_record(path, root):
    """Support per-group and recursive-root renderer manifests."""
    path,root=Path(path).resolve(),Path(root).resolve()
    folder=path.parent
    while True:
        candidate=folder/'render_manifest.json'
        if candidate.is_file():
            manifest=json.loads(candidate.read_text())
            key=path.relative_to(folder).as_posix()
            if key in manifest['files']:
                record=manifest['files'][key]
                if file_hash(path)!=record['wav_sha256']:
                    raise ValueError(f'WAV hash mismatch: {path}')
                return record
        if folder==root or root not in folder.parents:
            break
        folder=folder.parent
    raise ValueError(f'No matching render manifest for {path}')


def load_musdr(root):
    root=Path(root).resolve()
    paths=[root/'mueller_audio_tools/scapeplot.py',root/'mueller_audio_tools/ssm_features.py',
           root/'musdr/eval_metrics.py']
    if not all(p.is_file() for p in paths):
        raise ValueError(f'MusDr not found at {root}; see OPTIONAL_WORKFLOW.md')
    sys.path.insert(0,str(root))
    from mueller_audio_tools.scapeplot import normalization_properties_SSM,compute_fitness_scape_plot
    from mueller_audio_tools.ssm_features import (compute_tempo_rel_set,normalize_feature_sequence,
                                                  smooth_downsample_feature_sequence,compute_SM_TI,threshold_matrix)
    fingerprints={str(p.relative_to(root)):file_hash(p) for p in paths}
    return (normalization_properties_SSM,compute_fitness_scape_plot,compute_tempo_rel_set,
            normalize_feature_sequence,smooth_downsample_feature_sequence,compute_SM_TI,
            threshold_matrix,fingerprints)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--audio-root',type=Path,default=Path('runs/audio_trial'))
    parser.add_argument('--groups',nargs='+',default=['real','t08','t10','t12'])
    parser.add_argument('--limit-per-group',type=int,default=1)
    parser.add_argument('--start',type=float,default=0.)
    parser.add_argument('--duration',type=float,default=32.)
    parser.add_argument('--bounds',nargs=3,type=float,default=[3.,8.,15.])
    parser.add_argument('--musdr',type=Path,default=Path('HW2_scripts/MusDr'))
    parser.add_argument('--output',type=Path,default=Path('runs/metrics/si_trial'))
    args=parser.parse_args()
    if (args.limit_per_group<1 or not math.isfinite(args.start) or args.start<0
            or not math.isfinite(args.duration) or not 0<args.bounds[0]<args.bounds[1]<args.bounds[2]<args.duration):
        parser.error('Invalid crop or timescale settings')
    if len(args.groups)!=len(set(args.groups)) or any(Path(g).name!=g or g in ('.','..') for g in args.groups):
        parser.error('Groups must be distinct direct subdirectory names')
    try:
        import numpy as np
        import librosa
        (normalize_ssm,scape,tempo_set,normalize_features,smooth,compute_sm,threshold,
         source_hashes)=load_musdr(args.musdr)
        # Preflight all groups before any expensive computation.
        jobs=[]
        render_settings=None
        for group in args.groups:
            files=sorted((args.audio_root/group).glob('*.wav'))[:args.limit_per_group]
            if not files:
                raise ValueError(f'No WAV files for group {group}')
            for path in files:
                record=verified_audio_record(path,args.audio_root)
                if render_settings is None:
                    render_settings=record['settings']
                elif record['settings']!=render_settings:
                    raise ValueError(f'Render settings/SoundFont differ: {path}')
                if record['audio']['clipped_samples']:
                    raise ValueError(f'Clipped WAV must be rerendered before SI: {path}')
                with wave.open(str(path),'rb') as stream:
                    seconds=stream.getnframes()/stream.getframerate()
                # Match content duration; do not fill a short song with padding/tail.
                content_end=min(seconds,record['midi_duration_seconds'])
                if content_end+1e-6<args.start+args.duration:
                    raise ValueError(f'{path}: not enough musical content for this crop')
                jobs.append((group,path,record))
        versions={name:importlib.metadata.version(name) for name in ('numpy','scipy','librosa','numba')}
        protocol={'method':'MusDr Python SSM and fitness scape plot',
                  'scope':'pilot; first sorted WAVs in each group, not full-dataset results',
                  'start_seconds':args.start,'duration_seconds':args.duration,'bounds_seconds':args.bounds,
                  'audio_load_rate':22050,'chroma_hop':2205,'chroma_fft':4410,'chroma_tuning':0,'wrapper_sha256':file_hash(__file__),
                  'smooth_length':21,'downsample':5,'ssm_smooth_length':16,
                  'tempo_rel_min':.5,'tempo_rel_max':2.,'tempo_rel_count':7,
                  'pitch_shifts':list(range(12)),'threshold':.25,'penalty':-2,
                  'musdr_source_sha256':source_hashes,'versions':versions,'render_settings':render_settings}
        args.output.mkdir(parents=True,exist_ok=True)
        old_protocol=args.output/'protocol.json'
        if old_protocol.is_file() and json.loads(old_protocol.read_text())!=protocol:
            raise ValueError('Protocol differs from previous run; choose a new --output directory')
        save_json(old_protocol,protocol)
        records=[]
        for index,(group,path,render_record) in enumerate(jobs,1):
            folder=args.output/'cache'/group/path.stem
            folder.mkdir(parents=True,exist_ok=True)
            cache_key={'protocol':protocol,'wav_sha256':render_record['wav_sha256']}
            meta=folder/'metadata.json'
            started=time.monotonic()
            cached=(meta.is_file() and (folder/'fitness.npy').is_file() and (folder/'ssm.npy').is_file()
                    and json.loads(meta.read_text())['cache_key']==cache_key)
            if cached:
                details=json.loads(meta.read_text())
                fitness=np.load(folder/'fitness.npy',allow_pickle=False)
                feature_rate=details['feature_rate']
            else:
                print(f'[{index}/{len(jobs)}] {group}/{path.name}: loading {args.duration:g}s',flush=True)
                audio,sr=librosa.load(str(path),sr=22050,offset=args.start,duration=args.duration,mono=True)
                if abs(len(audio)/sr-args.duration)>1/sr:
                    raise ValueError('Unexpected cropped audio duration')
                # This is MusDr compute_SM_from_filename's sequence, using librosa's
                # modern keyword-only load API and cropping BEFORE feature extraction.
                chroma=librosa.feature.chroma_stft(y=audio,sr=sr,tuning=0,norm=2,hop_length=2205,n_fft=4410)
                features,feature_rate=smooth(chroma,sr/2205,filt_len=21,down_sampling=5)
                features=normalize_features(features,norm='2',threshold=.001)
                ssm,_=compute_sm(features,features,L=16,tempo_rel_set=tempo_set(.5,2,7),
                                 shift_set=np.arange(12),direction=2)
                ssm=threshold(ssm,thresh=.25,strategy='relative',scale=True,penalty=-2,binarize=False)
                ssm=normalize_ssm(ssm)
                print(f'  SSM {ssm.shape}; computing scape plot on CPU...',flush=True)
                fitness=scape(ssm)[0]
                np.save(folder/'ssm.npy',ssm)
                np.save(folder/'fitness.npy',fitness)
                details={'cache_key':cache_key,'feature_rate':float(feature_rate),
                         'compute_seconds':time.monotonic()-started,'shape':list(fitness.shape)}
                save_json(meta,details)
            values=si_values(fitness,feature_rate,args.duration,args.bounds)
            row={'group':group,'song_name':path.stem,'start_seconds':args.start,'duration_seconds':args.duration,
                 **values,'compute_seconds':details['compute_seconds'],'cached':cached,
                 'wav_sha256':render_record['wav_sha256']}
            records.append(row)
            with (args.output/'per_piece.csv').open('w',newline='') as stream:
                writer=csv.DictWriter(stream,fieldnames=list(row))
                writer.writeheader()
                writer.writerows(records)
            print(f'  {values}; original compute {details["compute_seconds"]:.2f}s; cached={cached}',flush=True)
        lines=['# SI 小量試算（非正式全組評分）','',
               f'每組取檔名排序前 {args.limit_per_group} 首，分析第 {args.start:g} 秒起的 {args.duration:g} 秒。',
               f'SI 時間尺度：short {args.bounds[0]:g}–{args.bounds[1]:g} 秒；'
               f'mid {args.bounds[1]:g}–{args.bounds[2]:g} 秒；long {args.bounds[2]:g}–{args.duration:g} 秒。','',
               '| 組別 | 首數 | SI short 平均 | SI mid 平均 | SI long 平均 | 原始計算秒數合計 |',
               '|---|---:|---:|---:|---:|---:|']
        for group in args.groups:
            subset=[r for r in records if r['group']==group]
            means=[statistics.mean(r['SI_'+name] for r in subset) for name in ('short','mid','long')]
            lines.append(f'| {group} | {len(subset)} | '+ ' | '.join(f'{x:.4f}' for x in means)
                         +f' | {sum(r["compute_seconds"] for r in subset):.2f} |')
        lines+=['','- 這是流程與時間成本測試，不能代表 20 首生成曲或 896 首真實曲的平均。',
                '- 不合併到原本 H4/GS 的 summary.csv，避免樣本數與片段範圍不同卻被當成同一實驗。',
                '- 統一音色、音量設定與時間長度；時間尺度單位是秒，並非小節。',
                '- SI 是指定範圍內的最大 fitness；不是原創性／抄襲檢測，也不是越高越好。',
                '- 有移調與速度相似性增強；結果依照 MusDr Python 版本計算。',
                '- 長片段運算成本增長很快，不能把本次秒數直接線性外推到完整長曲。',
                '- 來源與設定詳見 protocol.json；逐首值見 per_piece.csv。','']
        (args.output/'summary.md').write_text('\n'.join(lines))
        print(f'Finished: {args.output}/summary.md',flush=True)
    except (ImportError,ValueError,OSError,KeyError,wave.Error) as error:
        parser.exit(1,f'Error: {error}\nSee baseline/OPTIONAL_WORKFLOW.md for SI setup.\n')


if __name__=='__main__':
    main()
